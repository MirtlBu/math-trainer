/**
 * graph-stories.js
 * The stories used by the graph / equation word problems (graph-problems.js).
 *
 * One entry per story. Every story has these fields:
 *   dir      'up' (the quantity grows) or 'down' (it shrinks)
 *   y, x     the letters of the quantity and of the time-like variable
 *   unit     [singular, plural] of the unit of x ("each hour" / "every 2 hours")
 *   maxRate, cap   optional limits so the numbers stay believable
 *              (maxRate: largest rate per unit, cap: largest value of the quantity)
 *   intro    paragraph for the graph problems ("... is plotted below")
 *   eqIntro  paragraph for the equation problems
 *   fmt(n)   an amount with its unit ("3 slices", "€12")
 *   start(f), verb   build the statements: `${start(fmt(b))}, and then ${verb} ${fmt(p)} each hour.`
 *   askValue(x), askTime(y), askStart, askRate, askRateOver(k)   the questions
 *   yUnit, noun, rateMeaning, startMeaning   for "what does this number mean"
 * Names are Finnish. Add a story by copying an entry and changing the texts.
 */

